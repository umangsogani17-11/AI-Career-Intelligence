import re
from pathlib import Path
from uuid import uuid4

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import KeepTogether, Paragraph, SimpleDocTemplate, Spacer


OUTPUT_DIRECTORY = Path(__file__).resolve().parents[2] / "downloads"


def _text(value) -> str:
    """Turn either plain or structured AI fields into safe PDF text."""
    if isinstance(value, dict):
        value = " | ".join(str(item) for item in value.values() if item)
    return re.sub(r"\s+", " ", str(value or "")).strip()


def _bullet_items(values, style):
    return [Paragraph(f"• {_text(value)}", style) for value in values if _text(value)]


def _draw_page_number(canvas, document):
    canvas.saveState()
    canvas.setStrokeColor(colors.HexColor("#D8E5F7"))
    canvas.line(20 * mm, 16 * mm, 190 * mm, 16 * mm)
    canvas.setFillColor(colors.HexColor("#53657D"))
    canvas.setFont("Helvetica", 8)
    canvas.drawString(20 * mm, 10 * mm, "CareerOrbit · ATS-friendly resume draft")
    canvas.drawRightString(190 * mm, 10 * mm, f"Page {document.page}")
    canvas.restoreState()


def create_improved_resume_pdf(improvement: dict) -> str:
    """Create an ATS-friendly PDF and return its public download filename."""
    OUTPUT_DIRECTORY.mkdir(parents=True, exist_ok=True)
    filename = f"improved_resume_{uuid4().hex}.pdf"
    output_path = OUTPUT_DIRECTORY / filename

    styles = getSampleStyleSheet()
    title = ParagraphStyle(
        "ResumeTitle", parent=styles["Title"], fontName="Helvetica-Bold",
        fontSize=24, leading=29, textColor=colors.HexColor("#12243D"), alignment=TA_LEFT, spaceAfter=4,
    )
    subtitle = ParagraphStyle(
        "ResumeSubtitle", parent=styles["Normal"], fontName="Helvetica",
        fontSize=9, leading=13, textColor=colors.HexColor("#5A718D"), spaceAfter=14,
    )
    heading = ParagraphStyle(
        "SectionHeading", parent=styles["Heading2"], fontName="Helvetica-Bold",
        fontSize=11, leading=15, textColor=colors.HexColor("#0F766E"), spaceBefore=12, spaceAfter=6,
    )
    body = ParagraphStyle(
        "ResumeBody", parent=styles["BodyText"], fontName="Helvetica",
        fontSize=9.4, leading=14, textColor=colors.HexColor("#26384E"), spaceAfter=4,
    )
    bullet = ParagraphStyle("ResumeBullet", parent=body, leftIndent=10, firstLineIndent=-8, spaceAfter=3)
    project_name = ParagraphStyle("ProjectName", parent=body, fontName="Helvetica-Bold", textColor=colors.HexColor("#12243D"), spaceAfter=2)
    tech = ParagraphStyle("ProjectTech", parent=body, fontSize=8.4, textColor=colors.HexColor("#5A718D"), spaceAfter=8)

    story = [
        Paragraph("Improved Resume", title),
        Paragraph("Generated by CareerOrbit · Review details before submitting applications", subtitle),
    ]

    sections = [
        ("PROFESSIONAL SUMMARY", [improvement.get("professional_summary")]),
        ("TECHNICAL SKILLS", [", ".join(_text(item) for item in improvement.get("technical_skills", []) if _text(item))]),
        ("EDUCATION", improvement.get("education", [])),
    ]
    for section_name, values in sections:
        cleaned = [value for value in values if _text(value)]
        if cleaned:
            story.append(Paragraph(section_name, heading))
            story.extend(_bullet_items(cleaned, bullet))

    projects = improvement.get("projects", [])
    if projects:
        story.append(Paragraph("PROJECTS", heading))
        for project in projects:
            if not isinstance(project, dict):
                story.extend(_bullet_items([project], bullet))
                continue
            parts = [Paragraph(_text(project.get("name")) or "Project", project_name)]
            if _text(project.get("description")):
                parts.append(Paragraph(_text(project.get("description")), body))
            technologies = ", ".join(_text(item) for item in project.get("technologies", []) if _text(item))
            if technologies:
                parts.append(Paragraph(f"Technologies: {technologies}", tech))
            story.append(KeepTogether(parts))

    for section_name, field in [
        ("CERTIFICATIONS", "certifications"),
        ("ACHIEVEMENTS", "achievements"),
        ("SOFT SKILLS", "soft_skills"),
        ("ATS KEYWORDS", "ats_keywords"),
    ]:
        values = improvement.get(field, [])
        if values:
            story.append(Paragraph(section_name, heading))
            story.extend(_bullet_items(values, bullet))

    document = SimpleDocTemplate(
        str(output_path), pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm,
        topMargin=19 * mm, bottomMargin=23 * mm, title="Improved Resume",
    )
    document.build(story, onFirstPage=_draw_page_number, onLaterPages=_draw_page_number)
    return filename
